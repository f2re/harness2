_NATIVE_SLOTS = {"cc": threading.Semaphore(1), "ag": threading.Semaphore(1)}


def _native_concurrency(substrate: str) -> int:
    return max(1, config.WB_MAX_TRIALS[substrate] // config.WB_MAX_JOBS[substrate])


def _harness_slug(substrate: str) -> str:
    if substrate == "cc":
        return f"claude-harness/{config.WB_CC_HARNESS_VER}"
    if substrate == "ag":
        return f"antigravity-harness/{config.WB_AG_HARNESS_VER}"
    raise ValueError(f"not a native WorkBuddy substrate: {substrate!r}")


def _native_job_yaml(subset, substrate: str, label: str, tasks: list[str], ws: Path | None, k: int, jobs_dir: Path) -> str:
    selected = "\n".join(f"    - {task}" for task in tasks)
    hp: dict[str, str] = {}
    if ws is not None:
        hp["WB_HARNESS_WS"] = str(ws.resolve())
    extra = ""

    if substrate == "ag":
        if config.SOLVER_MODEL_AG:
            hp["AGY_MODEL"] = config.SOLVER_MODEL_AG
        hp["AGY_EFFORT"] = "high"
        hp["AGY_PRINT_TIMEOUT"] = "60m"
        hosts = ["generativelanguage.googleapis.com"]
        if config.ANTIGRAVITY_BASE_URL:
            host = urlparse(config.ANTIGRAVITY_BASE_URL).hostname
            if host and host not in hosts:
                hosts.append(host)
        host_lines = "\n".join(f"  - {host}" for host in hosts)
        env_lines = [f"  GEMINI_API_KEY: {json.dumps(config.ANTIGRAVITY_API_KEY)}"]
        if config.ANTIGRAVITY_BASE_URL:
            env_lines.append(
                f"  GOOGLE_GEMINI_BASE_URL: {json.dumps(config.ANTIGRAVITY_BASE_URL)}"
            )
        extra = (
            f"extra_allowed_hosts:\n{host_lines}\n"
            "environment_override:\n"
            "  mounts:\n"
            "    - type: bind\n"
            f"      source: {config.ANTIGRAVITY_DIST}\n"
            "      target: /opt/antigravity\n"
            "      read_only: true\n"
            "env_override:\n"
            + "\n".join(env_lines)
            + "\n"
        )

    hp_block = ""
    if hp:
        lines = "\n".join(f"  {key}: {json.dumps(value)}" for key, value in sorted(hp.items()))
        hp_block = f"harness_params_override:\n{lines}\n"
    judge = (
        f"llm_judge_override:\n  model: {subset.llm_judge_model}\n"
        if subset.llm_judge_model
        else ""
    )
    return (
        f"# GENERATED by harness2; ephemeral. label={label}\n"
        f"model: {config.WB_SOLVER_MODEL}\n"
        f"harness: {_harness_slug(substrate)}\n"
        f"dataset: datasets/{subset.dataset_id}/tasks\n"
        "harness_backend: local\n"
        f"model_connection: {config.WB_MODEL_CONNECTION}\n"
        f"n_attempts: {k}\n"
        f"jobs_dir: {jobs_dir}\n"
        "task_selection:\n"
        "  mode: name\n"
        "  names:\n"
        f"{selected}\n"
        "orchestrator_override:\n"
        f"  n_concurrent_trials: {_native_concurrency(substrate)}\n"
        f"{extra}{hp_block}{judge}"
    )


def _run_native_batch(
    subset,
    substrate: str,
    label_dir: Path,
    label: str,
    tasks: list[str],
    ws: Path | None,
    k: int,
    *,
    done,
    need=None,
    timeout_s: int | None = None,
) -> list[Path]:
    with _label_lock(label):
        todo = [task for task in tasks if not done(task)]
        if not todo:
            return []
        if need is not None:
            k = max(1, max(int(need(task)) for task in todo))
        before = set(_run_dirs(label_dir))
        digest = hashlib.sha1(f"{label}|{subset.name}|{sorted(todo)}".encode()).hexdigest()[:8]
        slug = f"{EPHEMERAL_PREFIX}{label_sanitize(label)[:40]}-{digest}"
        job = config.wb_repo() / "configs" / "jobs" / f"{slug}.yaml"
        label_dir.mkdir(parents=True, exist_ok=True)
        job.write_text(
            _native_job_yaml(subset, substrate, label, todo, ws, k, label_dir),
            encoding="utf-8",
        )
        timeout_s = timeout_s or int(
            (len(todo) * k / _native_concurrency(substrate)) * 3600 * 1.2 + 900
        )
        env = {
            **os.environ,
            "NO_FORCE_BUILD": "1",
            "HARNESS2_WB_VERTEX_URL": config.VERTEX_OPENAI_URL + "/chat/completions",
        }
        try:
            with _NATIVE_SLOTS[substrate]:
                proc = subprocess.Popen(
                    ["uv", "run", "./scripts/run.sh", "--job", slug],
                    cwd=config.wb_repo(),
                    env=env,
                    start_new_session=True,
                    stdout=subprocess.PIPE,
                    stderr=subprocess.PIPE,
                    text=True,
                )
                try:
                    _, stderr = proc.communicate(timeout=timeout_s)
                except subprocess.TimeoutExpired:
                    _kill_group(proc, signal.SIGTERM, grace=180)
                    stderr = "[timeout: WorkBuddy native job group killed]"
                if proc.returncode not in (0, None):
                    print(
                        f"[{time.strftime('%H:%M:%S')}] wb | {label}: run.sh exit "
                        f"{proc.returncode}; partial results retained :: {(stderr or '')[-300:]}",
                        flush=True,
                    )
        finally:
            job.unlink(missing_ok=True)
        return sorted(set(_run_dirs(label_dir)) - before)


class WbNativeAdapter(WbAdapter):
    """One WorkBuddy subset executed by Claude Code or Antigravity."""

    def __init__(
        self,
        subset: str = "office",
        *,
        substrate: str,
        split_file: Path | None = None,
        model: str | None = None,
    ):
        substrate = normalize_substrate(substrate)
        if subset not in SUBSETS:
            raise ValueError(f"unknown subset {subset!r}; one of {sorted(SUBSETS)}")
        if substrate not in ("cc", "ag"):
            raise ValueError("WbNativeAdapter requires substrate 'cc' or 'ag'")
        self.split_file = split_file
        self.subset = subset
        self.subset_info = SUBSETS[subset]
        self.spec = replace(
            spec_for(subset, "cx"),
            install_mode="claude_root" if substrate == "cc" else "antigravity_root",
            allow_subagents=True,
        )
        if substrate == "cc":
            self.model = model or config.SOLVER_MODEL_CC
            self.substrate = ClaudeSubstrate(launcher=self._launch_native)
        else:
            self.model = model or config.SOLVER_MODEL_AG
            self.substrate = AntigravitySubstrate(launcher=self._launch_native)

    def _cell_identity(self) -> dict:
        if self.substrate.name == "cc":
            return {
                "solver": config.SOLVER_MODEL_OC,
                "native_model": self.model,
                "cc_ver": config.WB_CC_HARNESS_VER,
                "connection": config.WB_MODEL_CONNECTION,
            }
        return {
            "solver": self.model or "antigravity-default",
            "ag_contract": config.WB_AG_HARNESS_VER,
            "connection": "direct-gemini",
        }

    def _launch_native(self, req, install) -> list[Path]:
        ws = None if install.fingerprint == "base" else install.staging_dir
        k = len(req.run_ids)
        label = self._label(req.run_ids[0], k)

        def have(task_id: str) -> int:
            return sum(
                1
                for trial in self._trials(label, task_id)
                if _trial_finished(trial)
                and _mark_matches(trial, install.fingerprint)
                and self._identity_matches(trial)
            )

        new_dirs = _run_native_batch(
            self.subset_info,
            self.substrate.name,
            self._label_dir(label),
            label,
            [req.task_ref],
            ws,
            k,
            done=lambda task: have(task) >= k,
            need=lambda task: k - have(task),
            timeout_s=req.timeout or None,
        )
        fresh = [
            trial
            for trial in _trials_in(new_dirs, req.task_ref, self.subset)
            if _trial_finished(trial)
        ]
        return self._rank(fresh)

    def trajectory_path(self, run_dir: Path) -> Path:
        stream = "cc-output.txt" if self.substrate.name == "cc" else "agy-output.jsonl"
        return Path(run_dir) / "agent" / stream

    def base_harness(self) -> Path:
        surface = self.substrate.surface()
        d = self.spec.runs_root / f"_base_harness_{self.substrate.name}_{os.getpid()}"
        if not HT.is_tree(surface, d):
            HT.write_tree(
                surface,
                {
                    "AGENTS.md": (
                        "Follow the task instructions and complete the requested work in the "
                        "workspace, writing every deliverable where the instructions say. "
                        "Verify the final artifact before finishing."
                    )
                },
                d,
                stubs=True,
            )
        return d

    def validate_tree(self, tree: dict[str, str]) -> None:
        # The portable native surface is already structurally validated by core.tree.
        return None

    def preflight(self) -> None:
        if shutil.which("uv") is None:
            raise RuntimeError("`uv` is not on PATH; WorkBuddy runs require uv")
        repo = config.wb_repo()
        if not (repo / "scripts" / "run.sh").is_file():
            raise RuntimeError(f"WorkBuddy checkout missing at {repo}; run harness2-setup wb")
        family, _, version = _harness_slug(self.substrate.name).partition("/")
        harness_cfg = repo / "configs" / "harnesses" / family / "versions" / f"{version}.yaml"
        if not harness_cfg.is_file():
            raise RuntimeError(f"WorkBuddy harness config missing at {harness_cfg}; rerun setup")
        if self.substrate.name == "cc":
            # The executable lives in the built WorkBuddy split mount, not necessarily on host.
            source = repo / "src" / "workbuddy_bench" / "agents" / "claude_harness_agent.py"
            if not source.is_file():
                raise RuntimeError("WorkBuddy Claude harness agent missing; rerun setup")
        else:
            staged = config.ANTIGRAVITY_DIST / "agy"
            if not staged.is_file():
                raise RuntimeError(
                    f"staged Antigravity binary missing at {staged}; run harness2-setup wb --substrate ag"
                )
            if not config.ANTIGRAVITY_API_KEY:
                raise RuntimeError(
                    "HARNESS2_ANTIGRAVITY_API_KEY (or GEMINI_API_KEY) is required for "
                    "containerized WorkBuddy Antigravity runs"
                )

    def _killed(self, run_dir: Path) -> bool:
        try:
            lines = self.trajectory_path(run_dir).read_text(
                encoding="utf-8", errors="replace"
            ).splitlines()
        except OSError:
            return False
        for line in reversed(lines):
            line = line.strip()
            if not line.startswith("{"):
                continue
            try:
                event = json.loads(line)
            except json.JSONDecodeError:
                return False
            if self.substrate.name == "ag" and event.get("event") == "result":
                result = event.get("result") if isinstance(event.get("result"), dict) else {}
                return result.get("status") not in (None, "SUCCESS")
            return event.get("type") == "error" or isinstance(event.get("error"), dict)
        return False


