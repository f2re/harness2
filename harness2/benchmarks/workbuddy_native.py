"""WorkBuddy-Bench native Claude Code and Antigravity cells.

WorkBuddy's verifier must run in the same Harbor trial that contains the agent,
so native substrates are expressed as installed-agent harnesses rather than host
side subprocesses. Claude reuses the pinned upstream ``CcAgent`` through a thin
harness-aware subclass; Antigravity uses the release-owned ``agy`` adapter.
"""

